"""cast — builds every character sprite from cast_parts + per-character heads and overlays.
    python3 tools/cast.py            writes game/art_chars.js and art/cast/<name>.png / .gif previews
"""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from spr import *
from cast_parts import *

HERE = os.path.dirname(__file__)
PREV = os.path.join(HERE, '..', 'art', 'cast'); os.makedirs(PREV, exist_ok=True)
ARMS_WALK = ['b', 'b', 'n', 'f', 'f', 'n']        # near arm swings against the near leg
CHARS = {}


def char(name, **kw): CHARS[name] = kw; return kw


def compose(parts):
    g = blank(32, 48)
    for p in parts:
        if p is not None: place(g, p)
    return g


def shift_rows(g, y0, y1, dy):
    """move rows y0..y1-1 down by dy (breathing while seated)"""
    n = copy(g)
    for y in range(y1 - 1, y0 - 1, -1):
        for x in range(32):
            if 0 <= y + dy < 48: n[y + dy][x] = g[y][x]
    for y in range(y0, y0 + dy):
        n[y] = ['.'] * 32
    return n


def build(name, d):
    frames = {}
    torso = d['torso']
    for f in ('se', 'ne'):
        head = rows_at(d['head'][f], 0)
        over = rows_at(d['over'][f], 0) if d.get('over') and d['over'].get(f) else None
        under = rows_at(d['under'][f], 0) if d.get('under') and d['under'].get(f) else None
        T = {k: rows_at(v, 17) for k, v in torso[f].items()}
        lower = d.get('lower', 'coat')
        def body(low, arm, bob):
            parts = [under, low, shift(T[arm], 0, bob)]
            if over: parts.append(shift(over, 0, bob))
            parts.append(shift(head, 0, bob))
            return ink(compose(parts))
        if lower == 'coat':
            n, fa = COAT_STAND[f]
            stand = coat_lower(f, 'stand', n, fa)
            walk = [(coat_lower(f, hem, nr, fr), bob) for hem, bob, nr, fr in COAT_WALK[f]]
        elif lower == 'suit':
            n, fa = COAT_STAND[f]
            stand = suit_lower(f, n, fa)
            walk = [(suit_lower(f, nr, fr), bob) for hem, bob, nr, fr in COAT_WALK[f]]
        elif lower == 'dress':
            feet = [(12, f + '_plant', 42), (18, f + '_plant', 42)] if f == 'se' else []
            stand = skirt(f, 0, feet)
            walk = [(skirt(f, sw, ft), DRESS_BOB[i]) for i, (sw, ft) in enumerate(DRESS_WALK[f])]
        # seated: torso + head drop; the lap/legs part replaces the lower body
        sk = d.get('sit', lower if lower != 'dress' else 'dress')
        if sk in SIT:
            lap = rows_at(SIT[sk][f], 37)
            parts = [under and shift(under, 0, SIT_DROP), lap, shift(T['n'], 0, SIT_DROP)]
            if over: parts.append(shift(over, 0, SIT_DROP))
            parts.append(shift(head, 0, SIT_DROP))
            sit = compose(parts)
            place(sit, lap)            # the lap sits in front of the coat skirt
            frames[f + '_sit0'] = ink(sit)
            s1 = compose([p for p in parts]); place(s1, lap)
            frames[f + '_sit1'] = ink(shift_rows(s1, 0, 37, 1))
        if d.get('sit_only'):
            continue
        frames[f + '_idle0'] = body(stand, 'n', 0)
        frames[f + '_idle1'] = body(stand, 'n', 1)
        for i, (low, bob) in enumerate(walk):
            frames[f'{f}_walk{i}'] = body(low, ARMS_WALK[i], bob)
        if 'aim' in T:
            frames[f + '_aim0'] = body(stand, 'aim', 0)
            a1 = copy(frames[f + '_aim0'])                    # recoil: the gun hand kicks up a pixel
            x0 = 24 if f == 'se' else 22
            for y in range(13, 26):
                for x in range(x0, 32): a1[y - 1][x] = a1[y][x] if a1[y][x] != '.' or y > 23 else a1[y - 1][x]
            frames[f + '_aim1'] = a1
    return frames


def dead(name, d):
    kind = d.get('dead', d.get('lower', 'coat'))
    g = G(DEAD[kind], 48)
    while len(g) < 20: g.append(['.'] * 48)
    if d.get('nohat'):
        for y in range(0, 4):
            for x in range(0, 14): g[y][x] = '.'
    return outline(copy(g), 'o')


ANIMS = "anims: { idle: { n: 2, ms: 42 }, walk: { n: 6, ms: 7 }, aim: { n: 1, ms: 30 }, sit: { n: 2, ms: 50 } }"

def main():
    import cast as C, cast_defs  # noqa: registers characters (into the imported module, not __main__)
    CHARS = C.CHARS
    out = ['// generated by tools/cast.py — do not edit by hand', '(function () { const S = Sprout;']
    for name, d in CHARS.items():
        fr = build(name, d)
        L = dict(o='ink', e='ink'); L.update(d['legend'])
        out.append(js_sprite(name, 32, 48, (16, 45), L, fr).replace('} });', '}, ' + ANIMS + ' });'))
        order = [k for k in fr]
        sheet([(k, fr[k]) for k in order], L, os.path.join(PREV, name + '.png'), k=5, cols=10)
        if 'se_walk0' in fr:
            gif([fr[f'se_walk{i}'] for i in range(6)] + [fr[f'ne_walk{i}'] for i in range(6)] * 1, L,
                os.path.join(PREV, name + '_walk.gif'), [110] * 12, k=5)
        print('char', name, len(fr), 'frames')
        if not d.get('sit_only') or d.get('dead'):
            dg = dead(name, d)
            out.append(js_sprite(name + '_dead', 48, 20, (24, 14), L, {'dead': dg}))
            sheet([('dead', dg)], L, os.path.join(PREV, name + '_dead.png'), k=5)
    out.append('})();')
    open(os.path.join(HERE, '..', 'game', 'art_chars.js'), 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
