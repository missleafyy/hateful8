# two boards nailed across the door, skewed along the wall (2:1 slope, wall runs right-down)
def _boards():
    """Two fresh planks nailed across the door, parallel to the wall (2:1, running right-down), nail heads near the ends."""
    W, H = 26, 30
    g = [['.'] * W for _ in range(H)]
    for top in (1, 12):                      # the two planks, 11 rows apart
        for x in range(1, W - 1):
            y = top + x // 2
            for k, c in enumerate('oWwdo'):  # outline, lit edge, face, shadow edge, outline
                if 0 <= y + k < H: g[y + k][x] = c
        for x in (1, W - 2):                 # square off the ends
            for k in range(5):
                g[top + x // 2 + k][x] = 'o'
        for nx in (4, W - 6):                # nails
            g[top + nx // 2 + 2][nx] = 'n'
    return [''.join(r) for r in g]
